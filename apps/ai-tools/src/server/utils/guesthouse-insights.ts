// 顧客分析（/guesthouse/insights）の「匙加減」を1か所に集約する設定モジュール。
// guesthouse-policy.ts（お客様チャットの方針）と同じ役割で、分析の軸を変えたいときはここだけを編集する。
//
// 設計の前提（2026-08）：
//   - 分析の材料は「お客さん日記＋聞き取りメモ」。阪中さんに新しい入力欄を足さない。
//     日記の itinerary には既にエリア内の動き（訪問先・泊数・前後の導線）が自由記述で入っており、
//     generateDiary のプロンプト側でそれを厚く書かせている。
//   - AI には**固定語彙**でタグ付けさせる。自由にタグを振らせると「食事」「料理」「ごはん」が
//     別タグになり、時系列で見ているものがゲストの変化ではなく語彙のブレになるため。
//   - 語彙を変えたら VOCAB_VERSION を上げる。キャッシュが全件作り直される。
//
// これから先の宿題（2026-08 時点でスコープ外にしたもの。忘れないようにここへ書いておく）：
//   - 不便・不満を「解決できるもの／できないもの」に分ける。設備の不備は直せるが、坂の勾配や
//     天気は直せない。分けられれば「読む」から「直す」へ一歩で進めるが、その判断は阪中さんの
//     手元の事情（費用・所有・季節）に依るので、AIに判定させる前に人が仕分ける画面が要る。
//   - 分析画面から「ここから何が言える？」とAIに聞けるミニチャット。下の buildAxisSuggestSystem
//     （軸の提案）が実際に役に立つと分かってから、その延長として考える。

import { ROUTE_SELF } from '~/utils/guesthouse-route'

/** 固定語彙のバージョン。下の語彙・抽出方針を変えたら必ず +1 する（既存の抽出結果が作り直される）。 */
// 2: 旅程の順番（route / routeIndex）と、宿と宿坊の分離（aspects.subject / shukuboStays）を追加。
// 3: 宿の体験とツアーの体験の分離（tourExperiences / 側面「ツアーでの体験」）、旅程に組み込まれた理由
//    （visitReason）、不便・不満を取りこぼさないための側面「その他」を追加。
export const VOCAB_VERSION = 3

/**
 * 滞在の型。「この地域の数日の中で宿がどんな位置を占めたか」を質的に捉える軸。
 * 時間配分（何時間を宿で過ごしたか）は日記から取れないが、役割なら読み取れる。
 */
export const STAY_TYPES = {
  base: '拠点型',
  destination: '目的地型',
  transit: '通過型',
  unknown: '不明',
} as const
export type StayTypeKey = keyof typeof STAY_TYPES

/** 滞在の型の判定基準（プロンプトに埋め込む）。ここを変えたら VOCAB_VERSION を上げる。 */
const STAY_TYPE_CRITERIA = `- "base"（拠点型）: 宿は主に寝る・休む場所で、旅の中心はエリア側にある（高野山の寺社を巡る、ハイキングをする等）。
- "destination"（目的地型）: 宿が用意した体験そのものが旅の目的の一部になっている（宿の案内する川遊び、農園の果物、宿の食事を目当てに来た等）。
- "transit"（通過型）: 移動の都合で1泊しただけで、このエリアでの活動がほとんど無い。
- "unknown": 判断できる材料が無い。`

/**
 * 満足度の側面（固定語彙）。日記・メモで触れられた側面だけを拾う。
 *
 * 「満足」と「宿が提供した体験」は別々の軸にすると同じ内容を二度数えることになるので、
 * 体験もこの側面のひとつ（宿での体験／ツアーでの体験）として満足度の軸に統合している。
 * 「その他」は、不便・不満がどの側面にも当てはまらないときの受け皿（不満を落とさないための枠）。
 */
export const SATISFACTION_ASPECTS = [
  '食事',
  '部屋・設備',
  '接客',
  '景観',
  '静けさ',
  '立地・交通',
  '宿での体験',
  'ツアーでの体験',
  '価格',
  'その他',
] as const

/**
 * 感想の主語（固定語彙）。一人のお客様の日記には、この宿の感想と、お客様が自分で手配した
 * 高野山の宿坊の感想が混ざる。混ぜたまま数えると「宿そのものの評価」が読めなくなるので、
 * 抽出の時点で分けておき、集計・表示も既定では inn（この宿）だけを見る。
 */
export const ASPECT_SUBJECTS = {
  inn: 'この宿',
  shukubo: '宿坊・ほかの宿',
  other: 'エリア・その他',
} as const
export type AspectSubjectKey = keyof typeof ASPECT_SUBJECTS

/** 主語の判定基準（プロンプトに埋め込む）。ここを変えたら VOCAB_VERSION を上げる。 */
const ASPECT_SUBJECT_CRITERIA = `- "inn": 阪中さんの**この宿**についての感想（この宿の食事・部屋・接客・宿からの眺め・宿の体験など）。
- "shukubo": お客様が**ご自身で手配した別の宿泊先**についての感想（高野山の宿坊、旅館、ホテル。精進料理・朝勤行・写経など宿坊で受けたものを含む）。
- "other": 宿ではなく、エリア側についての感想（観光地、外の食事処、交通、天候など）。`

/**
 * 関心の対象（固定語彙）。「何に心を動かされているか」の分類。
 * 満足度（何が良かった／気になったか）とは別の軸として独立させている。
 * 満足度が「宿への評価」なのに対し、こちらは「そのお客様がどんな人か」＝次の案内の手がかり。
 */
export const INTEREST_TOPICS = [
  '地域',
  '宿そのもの',
  '家族・同行者',
  '自然',
  '歴史・宗教',
  '食',
  '写真',
  '人との出会い',
] as const

/**
 * なぜこの宿が旅程に組み込まれたのか（固定語彙）。
 * 「旅程のどこに置かれるか（route）」と対にして、「なぜ置かれるか」を見るための軸。
 * 阪中さんのツアー参加者だから寄っている、のような組み込まれ方が見えると、
 * 経由地としての宿の位置づけ（拠点／目的地／通過）の理由まで読める。
 */
export const VISIT_REASONS = {
  tour: '阪中さんのツアー',
  koyasan: '高野山・エリア観光',
  nature: '田舎・自然の暮らし',
  transit: '移動の都合',
  people: '人とのつながり',
  price: '価格・空室の都合',
  unknown: '読み取れず',
} as const
export type VisitReasonKey = keyof typeof VISIT_REASONS

/** 旅程に組み込まれた理由の判定基準（プロンプトに埋め込む）。ここを変えたら VOCAB_VERSION を上げる。 */
const VISIT_REASON_CRITERIA = `- "tour": 阪中さんのツアー・案内に参加することが来訪の理由になっている。
- "koyasan": 高野山やエリアの観光・巡礼のために泊まっている（宿はそのための場所）。
- "nature": 田舎の暮らし・自然・農そのものを味わうために来ている。
- "transit": 移動の都合で経路上にあったから泊まった（次の目的地への通り道）。
- "people": 紹介・再訪・ホストや人に会うことが理由になっている。
- "price": 価格や空室の都合で選んだことが読み取れる。
- "unknown": 読み取れる材料が無い（**推測で埋めない**）。`

/**
 * 日記1件＝ゲスト1組から構造化データを抽出するシステムプロンプト。
 *
 * 満足度をあえて1〜5の点数にしていないのは、自由記述から数値を作らせると根拠のない精度が出てしまうため。
 * 「どの側面が、良い方向／悪い方向で語られたか」と、その根拠になった原文の引用だけを取り、
 * 集計側で「良い方向で語られた件数」を数える。件数なら n が小さくても嘘にならない。
 */
export function buildProfileExtractSystem(): string {
  const aspects = SATISFACTION_ASPECTS.map((a) => `"${a}"`).join(' / ')
  const topics = INTEREST_TOPICS.map((t) => `"${t}"`).join(' / ')
  const reasons = (Object.keys(VISIT_REASONS) as VisitReasonKey[]).join(' | ')

  return `あなたは、ゲストハウスのホスト「阪中さん」が書いた「お客さん日記」と「聞き取りメモ」を読み、後で集計できる構造化データに変換するアナリストです。

次の JSON のみを返す（前後に説明やコードブロック記号を付けない）:
{
  "stayType": "base | destination | transit | unknown",
  "nights": 今回の滞在の泊数（整数。本文に書かれていなければ必ず 0）,
  "originCountry": "国籍・出身（例: フランス / 日本。分からなければ空文字）",
  "prevStop": "この宿の前にいた場所（例: 大阪。分からなければ空文字）",
  "nextStop": "この宿の次に向かう場所（例: 京都。分からなければ空文字）",
  "route": ["旅程全体の経由地を通った順に並べた配列（下の「旅程の順番」に従う）。読み取れなければ空配列"],
  "routeIndex": route の中でこの宿が何番目か（1始まりの整数。route が空なら 0）,
  "shukuboStays": ["お客様がご自身で手配した、この宿以外の宿泊先の名前（例: 恵光院, 高野山の宿坊）。無ければ空配列"],
  "areaSpots": ["エリア内で訪れた場所（例: 奥之院, 壇上伽藍, 町石道）"],
  "innExperiences": ["**宿にいるあいだ**の体験で、宿が用意したもの（例: 宿の夕食, 囲炉裏, 朝の畑しごと）。無ければ空配列"],
  "tourExperiences": ["**ツアー・案内で外へ出て**得た体験（例: 川遊び, 柿の収穫, 桃の味, 集落の案内）。無ければ空配列"],
  "visitReason": "${reasons}",
  "aspects": [{ "subject": "inn | shukubo | other", "aspect": "側面", "sentiment": "positive | negative", "quote": "根拠になった原文の一部" }],
  "topics": ["関心の対象"],
  "beforeExpectation": "到着前に期待していたこと（分かる範囲。無ければ空文字）",
  "afterImpression": "滞在後の印象（分かる範囲。無ければ空文字）"
}

# 滞在の型（stayType）の判定
${STAY_TYPE_CRITERIA}

# 感想の主語（aspects の subject）— この宿と、お客様が自分で取った宿坊を必ず分ける
お客様は高野山の宿坊など、**ご自身で手配した別の宿**にも泊まっていることが多い。
その感想をこの宿の感想と混ぜると、宿そのものの評価が読めなくなるので、必ず主語で分ける。
${ASPECT_SUBJECT_CRITERIA}
主語がはっきりしない感想を、都合よく "inn" にしない。どちらの宿の話か本文から判断できないものは、その項目ごと出さない。

# 体験の分け方（innExperiences / tourExperiences）— 宿とツアーを必ず分ける
阪中さんは宿だけでなくツアー（川遊び・収穫・集落の案内など）もしている。
ツアーで得た体験（果物の味・活動の内容など）を宿の体験として数えると、**宿単体の感想**が読めなくなる。
- "innExperiences": 宿にいるあいだに、宿が用意したもの（宿の食事、風呂、囲炉裏、宿での語らい、宿の敷地でのこと）。
- "tourExperiences": 宿の外へ出て、阪中さんの案内・ツアーで得たもの（川遊び、柿や桃の収穫と味、山歩き、集落や畑の案内）。
- 感想（aspects）でも同じように、宿の中のことは "宿での体験"、ツアーのことは "ツアーでの体験" の側面にする。
- お客様がご自身で手配した宿坊で受けたもの（朝勤行・写経・精進料理）は、どちらにも入れない（aspects の subject="shukubo" だけで扱う）。
- 宿の中の話かツアーの話か判断できないものは、**どちらにも入れない**。

# 旅程に組み込まれた理由（visitReason）
なぜこの宿が旅程に入ったのかを、本文に書かれている手がかりからひとつ選ぶ。
${VISIT_REASON_CRITERIA}

# 不便・不満（sentiment: "negative"）— 遠慮せずに拾う
日記には良かったことが多く書かれるが、宿を良くする材料になるのは不便・不満の方なので、
**小さな引っかかりも必ず negative として拾う**。
- 「〜が少し分かりにくかった」「虫が多かった」「言葉が通じにくかった」「坂がきつかった」のような
  やわらかい言い方・遠回しな言い方も negative にする。
- どの側面にも当てはまらない不便は、側面を "その他" にして必ず残す（落とさない）。
- ただし、引用（quote）は必ず原文にある言葉から取る。原文に無いことを不満として作らない。

# 旅程の順番（route / routeIndex）
この宿の前後だけでなく、**旅全体のうち何番目にこの宿へ来たか**を見たいので、
日記・メモから読み取れる範囲で経由地を通った順に並べる。
- この宿での滞在も1地点として並びに入れる。その要素だけは地名ではなく、必ず 「${ROUTE_SELF}」 という文字列にする。
  例：東京から入り、高山・大阪を回ってこの宿に泊まり、そのあと高野山へ行って関西空港から帰る旅なら
  route は 東京 / 高山 / 大阪 / ${ROUTE_SELF} / 高野山 / 関西空港 の6地点、routeIndex は 4。
- 日付が書かれていなくてよい。「〜のあと」「次に」「最終日は」などの手がかりから順序を組み立てる。
- 同じ場所へ戻る往復は、実際に通った順にそのまま重複して並べる（大阪 / ${ROUTE_SELF} / 大阪 のように）。
- この宿以外の宿泊先（宿坊など）も1地点として地名で入れてよい。
- 地名は prevStop / nextStop と同じく短い固有名詞に正規化する。
- 順番が読み取れないときは route を空配列・routeIndex を 0 にする（**並び順を想像で作らない**）。

# 固定語彙（必ずこの中の語だけを使う。当てはまるものが無ければ、その項目は出さない）
- aspect: ${aspects}
- topics: ${topics}

# 方針
- **書かれていないことは絶対に補わない**。分からない項目は空文字・0・空配列にする。想像で埋めるくらいなら空にする。
  特に nights は要注意。「次回は2泊で来たい」のような**今回以外の滞在**の記述から今回の泊数を推測しない（この場合は 0）。
- aspects の "quote" は、必ず日記・メモに実際に書かれている文字列から取る（言い換えず、そのまま抜き出す）。
  引用が作れない側面は、その項目ごと出さない。
- prevStop / nextStop は集計してつなげるので、**短い地名だけ**を書く（「大阪から入り帰りも大阪へ」なら prevStop も nextStop も "大阪"）。
  国内の地名は日本語表記に統一する。行き先が空港なら "関西空港" のように書く。
- areaSpots も同様に、短い固有名詞に正規化する（「奥之院の杉並木を散策」→ "奥之院"）。
  宿泊先（宿坊・旅館・ホテル）は立ち寄り先ではないので areaSpots に入れず、shukuboStays に入れる。
- innExperiences / tourExperiences は**阪中さん側**が用意したものだけ。宿坊で受けた朝勤行・写経・精進料理はどちらにも入れない。
- 日本語で書く。`
}

/**
 * 「今の分析軸でいいのか」を、生データを読んだ AI に問い直すためのシステムプロンプト。
 *
 * 上の固定語彙は仮説で作ったもので、日記が増えると合わなくなる。だからといって AI に軸を
 * 自動で書き換えさせると、集計が語彙のブレに戻ってしまう。そこで「提案までは AI・採否は人」に分け、
 * ここでは**提案文を作るだけ**にしている（提案は保存もしない）。
 * 採用するときは、この画面の提案を見ながら上の固定語彙を人が書き換え、VOCAB_VERSION を上げる。
 */
export function buildAxisSuggestSystem(): string {
  const current = [
    `満足度の側面: ${SATISFACTION_ASPECTS.join(' / ')}`,
    `関心の対象: ${INTEREST_TOPICS.join(' / ')}`,
    `滞在の型: ${Object.values(STAY_TYPES).join(' / ')}`,
    `旅程に組み込まれた理由: ${Object.values(VISIT_REASONS).join(' / ')}`,
    `感想の主語: ${Object.values(ASPECT_SUBJECTS).join(' / ')}`,
    '旅程の順番（全N地点中M番目・前半/中盤/後半）',
  ].join('\n- ')

  return `あなたは、和歌山の山あいでゲストハウスとツアーを営む「阪中さん」の相談相手です。
阪中さんが書きためた「お客さん日記」と「聞き取りメモ」の生データを読み、
**次の一手（行動）につながるインサイトを得るには、どんな切り口で分類するとよいか**を提案してください。

次の JSON のみを返す（前後に説明やコードブロック記号を付けない）:
{
  "items": [
    {
      "title": "軸の名前（短く。例: 同行者のかたち）",
      "why": "この軸で分けると何が分かり、阪中さんがどう動けるようになるか（1〜2文）",
      "values": ["実際に分類するときの値の候補（3〜6個の固定語彙案）"],
      "evidence": "そう考えた根拠。日記に実際に出てきた言葉を引いて短く書く"
    }
  ],
  "redundant": ["今すでにある軸のうち、データを見ると重複している／ほとんど差が出ていないもの。無ければ空配列"]
}

# 今すでにある軸（これと同じものは提案しない）
- ${current}

# 方針
- **データの中に実際にある**手がかりから提案する。一般論のフレームワーク（RFM分析、ペルソナ等）を持ち込まない。
- 「見て面白い」ではなく「**分かったら阪中さんが何かを変えられる**」軸を優先する
  （案内の出し方を変える／ツアーの組み方を変える／設備を直す／受け入れる客層を選ぶ、など）。
- values は集計できる粒度にする。自由記述になってしまう軸は提案しない。
- 3〜5件にしぼる。無理に数を出さない。
- redundant は、根拠が言えるものだけ挙げる（言えなければ空配列）。
- 日本語で書く。断定しすぎず、根拠に基づく。`
}
